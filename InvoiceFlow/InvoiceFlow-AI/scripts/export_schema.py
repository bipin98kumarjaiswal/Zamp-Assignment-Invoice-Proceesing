"""Write db/schema_postgres.sql (and schema_sqlite.sql) from the SQLAlchemy models, for reference or manual setup."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sqlalchemy.dialects import postgresql, sqlite  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app.db import schema as S  # noqa: E402


def ddl(dialect) -> str:
    out = []
    for t in S.metadata.sorted_tables:
        out.append(str(CreateTable(t).compile(dialect=dialect)).strip() + ";")
        out += [str(CreateIndex(i).compile(dialect=dialect)).strip() + ";" for i in sorted(t.indexes, key=lambda x: x.name)]
    return "\n\n".join(out) + "\n"


(ROOT / "db").mkdir(exist_ok=True)
(ROOT / "db" / "schema_postgres.sql").write_text("-- Generated by scripts/export_schema.py. The app creates these tables itself on first start.\n\n" + ddl(postgresql.dialect()))
(ROOT / "db" / "schema_sqlite.sql").write_text("-- Generated by scripts/export_schema.py\n\n" + ddl(sqlite.dialect()))
print("wrote db/schema_postgres.sql and db/schema_sqlite.sql")
